# Standard resource actions Laravel registers (verb, action, name-suffix, uri-suffix)
# GET page actions only for the sweep (POST/PUT/DELETE are mutations, not FAB pages).
RESOURCE_GET_ACTIONS = [
    ('index',  ''),                # GET {uri}
    ('create', '/create'),          # GET {uri}/create
    ('show',   '/{id}'),            # GET {uri}/{id}
    ('edit',   '/{id}/edit'),      # GET {uri}/{id}/edit
]
# Non-page (mutation) actions — counted for completeness, not swept.
RESOURCE_MUTATION_ACTIONS = ['store', 'update', 'destroy']


# ---------------------------------------------------------------------------
# 1. Parse PHP return-array files (registry.php, action-registry.php)
# ---------------------------------------------------------------------------
def parse_flat_php_map(path: Path) -> 'OrderedDict[str, str]':
    """Extract `'key' => 'value',` pairs from a flat PHP return array."""
    out: 'OrderedDict[str, str]' = OrderedDict()
    if not path.is_file():
        return out
    text = path.read_text(encoding='utf-8')
    # Strip /* */ block comments and // line comments (but keep string contents).
    # Simple approach: match 'key' => 'value' lines directly (these files are flat).
    pattern = re.compile(r"'((?:[^'\\]|\\.)*)'\s*=>\s*'((?:[^'\\]|\\.)*)'\s*,?")
    for m in pattern.finditer(text):
        k = m.group(1).replace("\\'", "'")
        v = m.group(2).replace("\\'", "'")
        out[k] = v
    return out


def parse_modules_menu_keys(path: Path) -> 'dict[str, list[str]]':
    """Extract per-module menu_keys from modules.php.

    Returns {module_key: [menu_key, ...]} preserving order.
    Robust to the nested 'menus' => [ ... ] arrays.
    """
    if not path.is_file():
        return {}
    text = path.read_text(encoding='utf-8')
    # Find each top-level module block: "'modulekey' => [ ... 'menus' => [ ... ] ... ]"
    # We walk the top-level keys.
    modules: 'dict[str, list[str]]' = OrderedDict()
    # Match top-level entry: "    'key' => [" at 4-space indent.
    top_re = re.compile(r"^    '([a-zA-Z0-9-]+)'\s*=>\s*\[\s*$", re.MULTILINE)
    matches = list(top_re.finditer(text))
    for i, m in enumerate(matches):
        mod_key = m.group(1)
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        block = text[start:end]
        # Within this block, find the 'menus' => [ ... ] sub-array.
        menus_m = re.search(r"'menus'\s*=>\s*\[(.*?)\],", block, re.DOTALL)
        keys: list[str] = []
        if menus_m:
            inner = menus_m.group(1)
            for km in re.finditer(r"'([a-zA-Z0-9.-]+)'", inner):
                keys.append(km.group(1))
        modules[mod_key] = keys
    return modules


# ---------------------------------------------------------------------------
# 2. Load the 215 CSV page-route rows
# ---------------------------------------------------------------------------
def load_csv_rows() -> list:
    rows = []
    with CSV_PATH.open(encoding='utf-8') as f:
        data_lines = [ln for ln in f if not ln.lstrip().startswith('#')]
    reader = csv.DictReader(data_lines)
    for r in reader:
        rows.append(r)
    return rows


# ---------------------------------------------------------------------------
# 3. Scan authored content files -> set of menu_keys that HAVE content
# ---------------------------------------------------------------------------
def scan_authored_content() -> 'set[str]':
    """Return the set of menu_keys that HAVE an authored content file.

    Reads each file's internal ``'key' => '...'`` field (NOT the filename),
    because some files use a singular filename but a plural key
    (e.g. ``menus/sales/invoice.php`` declares ``'key' => 'sales.invoices'``).
    Falls back to ``"{module}.{slug}"`` derived from the path if no key field.
    """
    authored = set()
    menus_root = HELP_DIR / 'menus'
    if not menus_root.is_dir():
        return authored
    key_re = re.compile(r"'key'\s*=>\s*'([^']+)'")
    for mod_dir in sorted(menus_root.iterdir()):
        if not mod_dir.is_dir():
            continue
        for php in sorted(mod_dir.glob('*.php')):
            text = php.read_text(encoding='utf-8')
            m = key_re.search(text)
            if m:
                authored.add(m.group(1))
            else:
                authored.add(f"{mod_dir.name}.{php.stem}")
    return authored


# ---------------------------------------------------------------------------
# 4. Parse web.php Route::resource declarations -> runtime GET page routes
# ---------------------------------------------------------------------------
def parse_resource_routes() -> list:
    """Return list of {controller, uri_base, name_base, get_actions:[...]}.

    Each resource expands to index/create/show/edit GET page routes.
    Name base comes from ->names('X') if present, else derived from URI
    (admin/products -> admin.products). Controller is the short class name.
    """
    if not WEB_PHP.is_file():
        return []
    text = WEB_PHP.read_text(encoding='utf-8')

    # Slice to auth group only (resources outside auth are irrelevant).
    auth_marker = "Route::middleware('auth')"
    ai = text.find(auth_marker)
    if ai == -1:
        auth_text = text
    else:
        # Find the matching closing brace of the auth group.
        brace = text.find('{', ai)
        depth = 0
        j = brace
        while j < len(text):
            c = text[j]
            if c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
                if depth == 0:
                    break
            j += 1
        auth_text = text[ai:j + 1] if j < len(text) else text[ai:]

    resources = []
    # Match Route::resource('uri', ControllerClass) optionally ->names('X') ...
    # Statement ends at ';' on the resource line (chained calls may wrap, but
    # here they're single-line). Capture the whole statement up to ';'.
    res_re = re.compile(
        r"Route::resource\(\s*"
        r"(?:'([^']+)'|\"([^\"]+)\")\s*,\s*"
        r"([A-Za-z_\\][\w\\]*)\s*"
        r"(?:::class)?\s*\)"
        r"([^;]*)",
        re.DOTALL,
    )
    for m in res_re.finditer(auth_text):
        uri = m.group(1) or m.group(2) or ''
        controller_full = m.group(3)
        tail = m.group(4) or ''
        # Short controller name (strip namespace).
        short_ctrl = controller_full.split('\\')[-1]
        # Name base from ->names('X'); else derive from uri (a/b -> a.b).
        nm = re.search(r"->names\(\s*'([^']+)'\s*\)", tail)
        if nm:
            name_base = nm.group(1)
        else:
            name_base = uri.replace('/', '.')
        # Detect ->only()/->except() (none in this codebase, but handle anyway).
        only_m = re.search(r"->only\(\s*\[([^\]]*)\]\s*\)", tail)
        except_m = re.search(r"->except\(\s*\[([^\]]*)\]\s*\)", tail)
        all_actions = [a for a, _ in RESOURCE_GET_ACTIONS]
        if only_m:
            allowed = re.findall(r"'([^']+)'", only_m.group(1))
            actions = [a for a in all_actions if a in allowed]
        elif except_m:
            excluded = re.findall(r"'([^']+)'", except_m.group(1))
            actions = [a for a in all_actions if a not in excluded]
        else:
            actions = list(all_actions)
        resources.append({
            'controller': short_ctrl,
            'uri_base': uri,
            'name_base': name_base,
            'get_actions': actions,
        })
    return resources


# ---------------------------------------------------------------------------
# 5. The 4-layer resolution chain (mirrors HelpService::menuKeyForRoute)
# ---------------------------------------------------------------------------
def resolve(route_name, controller, action, registry, action_registry):
    """Return (layer, resolved_key). layer 4 => (4, None).

    controller/action may be None (closure / unnamed route).
    """
    if route_name and route_name in registry:
        return (1, registry[route_name])
    if controller and action:
        ca = f'{controller}@{action}'
        if ca in action_registry:
            return (2, action_registry[ca])
        if controller:
            wc = f'{controller}@*'
            if wc in action_registry:
                return (3, action_registry[wc])
    return (4, None)


# ---------------------------------------------------------------------------
# MAIN
# ---------------------------------------------------------------------------
def main():
    registry = parse_flat_php_map(HELP_DIR / 'registry.php')
    action_registry = parse_flat_php_map(HELP_DIR / 'action-registry.php')
    modules_menus = parse_modules_menu_keys(HELP_DIR / 'modules.php')
    csv_rows = load_csv_rows()
    authored = scan_authored_content()
    resources = parse_resource_routes()

    all_known_menu_keys = set()
    for keys in modules_menus.values():
        all_known_menu_keys.update(keys)

    # Separate action_registry into per-action and wildcard for stats.
    wildcard_keys = {k: v for k, v in action_registry.items() if k.endswith('@*')}
    per_action_keys = {k: v for k, v in action_registry.items() if not k.endswith('@*')}

    print('=' * 72)
    print('PHASE 6 — EMPTY-STATE SWEEP + REGISTRY BACKFILL AUDIT')
    print('=' * 72)
    print(f'registry.php             : {len(registry):>4} route_name -> menu_key mappings')
    print(f'action-registry.php     : {len(per_action_keys):>4} controller@action mappings')
    print(f'                          + {len(wildcard_keys):>4} controller@* wildcards')
    print(f'modules.php              : {len(modules_menus):>4} modules, '
          f'{sum(len(v) for v in modules_menus.values())} menu_keys listed')
    print(f'unique menu_keys (union) : {len(all_known_menu_keys):>4}')
    print(f'authored content files   : {len(authored):>4}  -> {sorted(authored)}')
    print(f'CSV page-route rows      : {len(csv_rows):>4}')
    print(f'Route::resource decls    : {len(resources):>4}')
    print()

    # ------------------------------------------------------------------
    # SWEEP A — the 215 curated CSV page routes (run the chain)
    # ------------------------------------------------------------------
    matrix = []  # rows for the CSV matrix
    layer_counts = defaultdict(int)
    null_routes = []
    content_missing = []  # resolved key but no content file
    csv_route_names = set()

    # Documented route-name aliases: the CSV carries a legacy alias row whose
    # menu_key differs from the registry's primary mapping (by design — both
    # sidebar entries describe the SAME page). These are EXPECTED, not gaps.
    KNOWN_ALIASES = {
        'admin.branch-demands.index': ('inventory.branch-demand', 'finance.branch-demand'),
    }

    for r in csv_rows:
        route_name = r['route_name'].strip()
        controller = r['controller'].strip()
        action = r['action'].strip()
        menu_key_csv = r['menu_key'].strip()
        module = r['module'].strip()
        uri = r['uri'].strip()
        csv_route_names.add(route_name)

        layer, resolved = resolve(route_name, controller, action, registry, action_registry)
        layer_counts[layer] += 1
        has_content = resolved in authored if resolved else False
        # Consistency: does resolved match the CSV's menu_key?
        alias = KNOWN_ALIASES.get(route_name)
        if alias and resolved == alias[1] and menu_key_csv == alias[0]:
            csv_match = 'expected-alias'
        elif resolved == menu_key_csv:
            csv_match = 'yes'
        else:
            csv_match = 'NO-MISMATCH'

        matrix.append({
            'source': 'csv',
            'route_name': route_name,
            'uri': uri,
            'controller': controller,
            'action': action,
            'csv_menu_key': menu_key_csv,
            'resolved_layer': layer,
            'resolved_menu_key': resolved or '',
            'content_exists': 'yes' if has_content else 'no',
            'csv_match': csv_match,
            'module': module,
        })

        if layer == 4:
            null_routes.append((route_name, controller, action, uri, module, menu_key_csv))
        elif not has_content:
            content_missing.append((route_name, resolved, module))

    # ------------------------------------------------------------------
    # SWEEP B — resource-expanded runtime GET page routes (collapsed ones)
    # ------------------------------------------------------------------
    # For each resource, expand to its GET actions (index/create/show/edit)
    # and resolve. These mostly rely on the controller@* wildcard (layer 3).
    resource_runtime_routes = []
    resource_null = []
    wildcard_missing_controllers = set()
    for res in resources:
        ctrl = res['controller']
        name_base = res['name_base']
        uri_base = res['uri_base']
        # Verify wildcard exists for this controller.
        wc = f'{ctrl}@*'
        has_wc = wc in action_registry
        if not has_wc:
            wildcard_missing_controllers.add(ctrl)
        for act, suffix in RESOURCE_GET_ACTIONS:
            if act not in res['get_actions']:
                continue
            rn = f'{name_base}.{act}'
            full_uri = f'{uri_base}{suffix}'
            layer, resolved = resolve(rn, ctrl, act, registry, action_registry)
            has_content = resolved in authored if resolved else False
            resource_runtime_routes.append({
                'source': 'resource',
                'route_name': rn,
                'uri': full_uri,
                'controller': ctrl,
                'action': act,
                'resolved_layer': layer,
                'resolved_menu_key': resolved or '',
                'content_exists': 'yes' if has_content else 'no',
                'has_wildcard': 'yes' if has_wc else 'MISSING',
            })
            if layer == 4:
                resource_null.append((rn, ctrl, act, full_uri, 'MISSING-WILDCARD' if not has_wc else 'no-wc-resolve'))

    # ------------------------------------------------------------------
    # SWEEP C — orphan explicit GET routes (in routes.tsv, not in CSV)
    # These are explicit Route::get calls that P1 may have skipped (AJAX, etc).
    # We re-extract from web.php the named GET routes inside auth group.
    # ------------------------------------------------------------------
    orphan_routes = []
    tsv_available = TSV_PATH is not None and TSV_PATH.is_file()
    if tsv_available:
        with TSV_PATH.open(encoding='utf-8') as fh:
            tsv_rows = list(csv.DictReader(fh, delimiter='\t'))
        for tr in tsv_rows:
            # TSV header: LINE, VERB, URI, CONTROLLER, ACTION, NAME, PREFIX (uppercase).
            verb = tr.get('VERB', '').strip()
            name = tr.get('NAME', '').strip()
            ctrl = tr.get('CONTROLLER', '').strip()
            act = tr.get('ACTION', '').strip()
            uri = tr.get('URI', '').strip()
            if verb != 'GET':
                continue
            if not name or '.* (resource)' in name:
                continue
            if ctrl == '(closure)':
                continue
            if name in csv_route_names:
                continue  # already swept via CSV
            # Resolve.
            layer, resolved = resolve(name, ctrl, act, registry, action_registry)
            has_content = resolved in authored if resolved else False
            orphan_routes.append({
                'source': 'orphan',
                'route_name': name,
                'uri': uri,
                'controller': ctrl,
                'action': act,
                'resolved_layer': layer,
                'resolved_menu_key': resolved or '',
                'content_exists': 'yes' if has_content else 'no',
            })

    # ------------------------------------------------------------------
    # ANALYSIS — null classification
    # ------------------------------------------------------------------
    # Classify CSV null routes. Intentional skips = routes whose action is
    # clearly non-page (ajax, export, download, fragment) OR whose menu_key
    # in CSV is empty. Gap = a route with a menu_key that didn't resolve.
    INTENTIONAL_PATTERNS = re.compile(
        r'(ajax|fragment|export|download|stream|print-|slip$|preview|modal|receive-modal|'
        r'cutover|drift|comparison|comparisons|drill-down|health-summary|status)',
        re.IGNORECASE,
    )

    csv_null_classified = []
    for (rn, ctrl, act, uri, module, mk) in null_routes:
        is_intentional = bool(INTENTIONAL_PATTERNS.search(rn) or INTENTIONAL_PATTERNS.search(act))
        csv_null_classified.append({
            'route_name': rn, 'controller': ctrl, 'action': act, 'uri': uri,
            'module': module, 'csv_menu_key': mk,
            'classification': 'intentional-skip' if is_intentional else 'REGISTRY-GAP',
        })

    # ------------------------------------------------------------------
    # Phase 7 authoring worklist: menu_keys with NO content file
    # ------------------------------------------------------------------
    # Compute how many routes each menu_key serves (across all 3 sweeps).
    # High-impact keys (many routes) should be authored first in Phase 7.
    key_route_counts = defaultdict(int)
    for r in matrix:
        if r['resolved_menu_key']:
            key_route_counts[r['resolved_menu_key']] += 1
    for r in resource_runtime_routes:
        if r['resolved_menu_key']:
            key_route_counts[r['resolved_menu_key']] += 1
    for r in orphan_routes:
        if r['resolved_menu_key']:
            key_route_counts[r['resolved_menu_key']] += 1

    worklist = OrderedDict()
    for mod_key, mod_menus in modules_menus.items():
        missing = [k for k in mod_menus if k not in authored]
        present = [k for k in mod_menus if k in authored]
        worklist[mod_key] = {
            'total': len(mod_menus),
            'authored': len(present),
            'missing': len(missing),
            'missing_keys': missing,
            'present_keys': present,
        }

    # ------------------------------------------------------------------
    # Write matrix CSV
    # ------------------------------------------------------------------
    MATRIX_OUT.parent.mkdir(parents=True, exist_ok=True)
    with MATRIX_OUT.open('w', encoding='utf-8', newline='') as f:
        w = csv.writer(f)
        w.writerow(['source', 'route_name', 'uri', 'controller', 'action',
                    'csv_menu_key', 'resolved_layer', 'resolved_menu_key',
                    'content_exists', 'csv_match', 'module'])
        for row in matrix:
            w.writerow([row['source'], row['route_name'], row['uri'], row['controller'],
                        row['action'], row['csv_menu_key'], row['resolved_layer'],
                        row['resolved_menu_key'], row['content_exists'], row['csv_match'],
                        row['module']])
        for row in resource_runtime_routes:
            w.writerow([row['source'], row['route_name'], row['uri'], row['controller'],
                        row['action'], '', row['resolved_layer'], row['resolved_menu_key'],
                        row['content_exists'], row['has_wildcard'], ''])
        for row in orphan_routes:
            w.writerow([row['source'], row['route_name'], row['uri'], row['controller'],
                        row['action'], '', row['resolved_layer'], row['resolved_menu_key'],
                        row['content_exists'], '', ''])

    # ------------------------------------------------------------------
    # Console summary
    # ------------------------------------------------------------------
    total_csv = len(csv_rows)
    total_resource = len(resource_runtime_routes)
    total_orphan = len(orphan_routes)
    print('-' * 72)
    print(f'SWEEP A — CSV curated page routes: {total_csv}')
    print(f'  layer 1 (route-name match)   : {layer_counts[1]:>4}')
    print(f'  layer 2 (controller@action)  : {layer_counts[2]:>4}')
    print(f'  layer 3 (controller@* wc)    : {layer_counts[3]:>4}')
    print(f'  layer 4 (NULL / empty-state) : {layer_counts[4]:>4}')
    mismatches = [r for r in matrix if r['csv_match'] == 'NO-MISMATCH']
    print(f'  resolved != csv menu_key     : {len(mismatches):>4}  (should be 0)')
    print()
    print(f'SWEEP B — resource-expanded GET routes: {total_resource}')
    res_layer = defaultdict(int)
    for r in resource_runtime_routes:
        res_layer[r['resolved_layer']] += 1
    print(f'  layer 1/2/3/4 : {res_layer[1]}/{res_layer[2]}/{res_layer[3]}/{res_layer[4]}')
    print(f'  controllers with MISSING @* wildcard: {len(wildcard_missing_controllers)}')
    if wildcard_missing_controllers:
        print(f'    -> {sorted(wildcard_missing_controllers)}')
    print()
    print(f'SWEEP C — orphan named GET routes (not in CSV): {total_orphan}')
    orph_layer = defaultdict(int)
    for r in orphan_routes:
        orph_layer[r['resolved_layer']] += 1
    print(f'  layer 1/2/3/4 : {orph_layer[1]}/{orph_layer[2]}/{orph_layer[3]}/{orph_layer[4]}')
    print()
    print('NULL CLASSIFICATION (CSV layer-4 routes):')
    gaps = [c for c in csv_null_classified if c['classification'] == 'REGISTRY-GAP']
    skips = [c for c in csv_null_classified if c['classification'] == 'intentional-skip']
    print(f'  intentional-skip : {len(skips)}')
    print(f'  REGISTRY-GAP     : {len(gaps)}')
    if gaps:
        print('  GAPS to backfill:')
        for g in gaps:
            print(f"    {g['route_name']:<45} {g['controller']}@{g['action']:<20} csv_key={g['csv_menu_key']}")
    print()
    print('CONTENT COVERAGE (Phase 7 worklist):')
    total_menu = sum(v['total'] for v in worklist.values())
    total_auth = sum(v['authored'] for v in worklist.values())
    total_miss = sum(v['missing'] for v in worklist.values())
    print(f'  total menu_keys in modules.php : {total_menu}')
    print(f'  authored content files         : {total_auth}')
    print(f'  MISSING (Phase 7 to author)    : {total_miss}')
    print()
    print(f'Wrote: {MATRIX_OUT}')
    print(f'Wrote: {REPORT_OUT}')

    # ------------------------------------------------------------------
    # Write markdown report
    # ------------------------------------------------------------------
    write_report(registry, action_registry, modules_menus, authored, csv_rows,
                 matrix, layer_counts, resource_runtime_routes, res_layer,
                 wildcard_missing_controllers, orphan_routes, orph_layer,
                 csv_null_classified, gaps, skips, worklist,
                 total_menu, total_auth, total_miss, key_route_counts)


def write_report(registry, action_registry, modules_menus, authored, csv_rows,
                 matrix, layer_counts, resource_runtime_routes, res_layer,
                 wildcard_missing_controllers, orphan_routes, orph_layer,
                 csv_null_classified, gaps, skips, worklist,
                 total_menu, total_auth, total_miss, key_route_counts):
    L = []
    L.append('# 📊 Help System — Phase 6 Coverage Report')
    L.append('')
    L.append('> **Empty-state sweep + registry backfill audit.**')
    L.append('> Generated by `parse_work/phase6_sweep.py` from the live')
    L.append('> `resources/help/` registries + `docs/help-inventory.csv` + `routes/web.php`.')
    L.append('')
    L.append('This report is the **definitive Phase 7 authoring worklist** and the registry')
