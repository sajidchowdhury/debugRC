#!/usr/bin/env python3
"""
Phase 6 — Empty-state sweep + registry backfill audit.

For EVERY authenticated GET page route in routes/web.php, simulate the
HelpService 4-layer resolution chain and record:
    route_name -> controller@action -> resolved_layer (1/2/3/4-null)
                 -> resolved_menu_key -> content_file_exists (yes/no)

Layer meaning (matches HelpService::menuKeyForRoute):
    1 = exact route-name match       (resources/help/registry.php)
    2 = controller@action match      (resources/help/action-registry.php)
    3 = controller@* wildcard        (resources/help/action-registry.php)
    4 = null -> empty-state card     (registry gap OR intentional skip)

Outputs:
  - docs/help-coverage-matrix.csv   (route-level matrix)
  - docs/help-coverage-report.md    (module summary + null classification + Phase 7 worklist)
  - console summary + backfill candidates

Also expands Route::resource() declarations to count the true runtime GET
page routes (index/create/show/edit) and verify each controller's @* wildcard
exists so collapsed resource actions resolve.
"""
