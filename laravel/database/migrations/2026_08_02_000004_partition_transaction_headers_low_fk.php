 *   5. sales_returns           — by return_date       (2 inbound FKs, soft deletes, LISTEN/NOTIFY)
 *   6. purchase_receives       — by receive_date      (3 inbound FKs, soft deletes)
 *   7. purchase_returns        — by return_date       (1 inbound FK, soft deletes)
 *   8. damage_invoices         — by damage_date       (3 inbound FKs, soft deletes, LISTEN/NOTIFY, 34 columns)
 *   9. manual_journals         — by journal_date      (1 inbound FK, soft deletes, audit trigger)
 *
 * DESIGN DECISIONS:
 *
 * 1. Composite PK: PK(id) → PK(id, date_column). GENERATED ALWAYS → GENERATED BY DEFAULT
 *    for OVERRIDING SYSTEM VALUE during data copy.
 *
 * 2. UNIQUE constraints must include partition key: e.g. UNIQUE(code) → UNIQUE(code, date_column).
 *    This is a PostgreSQL requirement for partitioned tables.
 *
 * 3. Trigger-based FK conversion for Group B: When a partitioned table is referenced by
 *    a declarative FK from another table, PostgreSQL cannot enforce it. We drop the
 *    declarative FK and create a trigger that checks existence in the partitioned parent.
 *    Also need cascade delete triggers for ON DELETE CASCADE FKs.
 *
 * 4. Triggers: updated_at, audit, and LISTEN/NOTIFY triggers are preserved on the
 *    partitioned parent. They automatically apply to all partitions.
 *
 * 5. RLS: All tables have RLS policies. Policies on the parent apply to all partitions.
 *
 * 6. Soft deletes: Tables with `deleted_at` need it included in the partitioned schema.
 *
 * 7. damage_invoices.employee_ledger_entry_id → employee_ledger(id): This FK references
 *    a partitioned table (Phase 2). It must be converted to trigger-based FK as well.
 *
