 *   2. employee_transactions   — by transaction_date  (branch RLS, updated_at trigger, audit trigger)
 *   3. other_incomes           — by income_date       (branch RLS, updated_at trigger, audit trigger)
 *   4. other_expenses          — by expense_date      (branch RLS, updated_at trigger, audit trigger)
 *
