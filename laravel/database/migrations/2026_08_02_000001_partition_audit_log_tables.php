        if ($this->isAlreadyPartitioned('stock_adjustment_audit_log')) {
            return;
        }

        // ── Drop RLS policies on old table ──
        foreach (['select', 'insert', 'update', 'delete', 'admin'] as $verb) {
            DB::statement(
                "DROP POLICY IF EXISTS rls_stock_adjustment_audit_log_{$verb} ON stock_adjustment_audit_log"
            );
        }
        DB::statement('ALTER TABLE stock_adjustment_audit_log NO FORCE ROW LEVEL SECURITY');
        DB::statement('ALTER TABLE stock_adjustment_audit_log DISABLE ROW LEVEL SECURITY');

        // ── Drop indexes on old table ──
        $saalIndexes = [
            'idx_saal_adjustment', 'idx_saal_critical', 'idx_saal_branch', 'idx_saal_actor',
        ];
        foreach ($saalIndexes as $idx) {
            DB::statement("DROP INDEX IF EXISTS {$idx}");
        }

        // ── Rename old table ──
        DB::statement(
            'ALTER TABLE stock_adjustment_audit_log RENAME TO stock_adjustment_audit_log_unpartitioned'
        );

        // ── Create partitioned table ──
        // Note: original uses bigserial, we switch to GENERATED BY DEFAULT AS IDENTITY
        // for consistency with partitioned table pattern
        DB::statement(<<<'SQL'
            CREATE TABLE stock_adjustment_audit_log (
                id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
                stock_adjustment_id INTEGER NOT NULL REFERENCES stock_adjustments(id) ON DELETE CASCADE,
                branch_id           INTEGER NOT NULL REFERENCES branches(id),
                action VARCHAR(40) NOT NULL CHECK (
                    action IN ('create','update','submit','approve','reject','confirm',
                               'cancel','reverse','force_confirm','reopen','delete','export','print')
                ),
                actor_id   BIGINT,
                actor_role VARCHAR(40),
                payload    JSONB,
                ip_address VARCHAR(45),
                user_agent VARCHAR(255),
                created_at TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY (id, created_at)
            ) PARTITION BY RANGE (created_at)
        SQL);

        // ── Create partitions ──
        $this->createPreYearPartition('stock_adjustment_audit_log', 'pre2026', '2026');
        $this->createMonthlyPartitions('stock_adjustment_audit_log', '2026');

        // ── Copy data ──
        DB::statement(<<<'SQL'
            INSERT INTO stock_adjustment_audit_log (
                id, stock_adjustment_id, branch_id, action, actor_id,
                actor_role, payload, ip_address, user_agent, created_at
            )
            OVERRIDING SYSTEM VALUE
            SELECT
                id, stock_adjustment_id, branch_id, action, actor_id,
                actor_role, payload, ip_address, user_agent, created_at
            FROM stock_adjustment_audit_log_unpartitioned
            ORDER BY created_at, id
        SQL);

        // ── Fix sequence ──
        $this->fixSequence('stock_adjustment_audit_log');

        // ── Recreate indexes ──
        DB::statement(
            'CREATE INDEX idx_saal_adjustment ON stock_adjustment_audit_log (stock_adjustment_id, created_at)'
        );
        DB::statement(<<<'SQL'
            CREATE INDEX idx_saal_critical ON stock_adjustment_audit_log (stock_adjustment_id)
                WHERE action IN ('confirm','cancel','reverse','force_confirm')
        SQL);
        DB::statement(
            'CREATE INDEX idx_saal_branch ON stock_adjustment_audit_log (branch_id, created_at)'
        );
        DB::statement(
            'CREATE INDEX idx_saal_actor ON stock_adjustment_audit_log (actor_id, created_at)'
        );
        DB::statement(<<<'SQL'
            CREATE INDEX idx_saal_created_at_brin
                ON stock_adjustment_audit_log USING BRIN (created_at)
                WITH (pages_per_range = 32)
        SQL);

        // ── Drop old table ──
        DB::statement('DROP TABLE stock_adjustment_audit_log_unpartitioned');

        // ── Recreate RLS policies ──
        DB::statement('ALTER TABLE stock_adjustment_audit_log ENABLE ROW LEVEL SECURITY');
        DB::statement('ALTER TABLE stock_adjustment_audit_log FORCE ROW LEVEL SECURITY');

        DB::statement(<<<'SQL'
            CREATE POLICY rls_stock_adjustment_audit_log_select ON stock_adjustment_audit_log
                FOR SELECT USING (
                    current_setting('app.is_admin', true) = 'true'
                    OR branch_id = current_setting('app.branch_id', true)::integer
                )
        SQL);
        DB::statement(<<<'SQL'
            CREATE POLICY rls_stock_adjustment_audit_log_insert ON stock_adjustment_audit_log
                FOR INSERT WITH CHECK (
                    current_setting('app.is_admin', true) = 'true'
                    OR branch_id = current_setting('app.branch_id', true)::integer
                )
        SQL);
        DB::statement(<<<'SQL'
            CREATE POLICY rls_stock_adjustment_audit_log_update ON stock_adjustment_audit_log
                FOR UPDATE USING (
                    current_setting('app.is_admin', true) = 'true'
                    OR branch_id = current_setting('app.branch_id', true)::integer
                )
                WITH CHECK (
                    current_setting('app.is_admin', true) = 'true'
                    OR branch_id = current_setting('app.branch_id', true)::integer
                )
        SQL);
        DB::statement(<<<'SQL'
            CREATE POLICY rls_stock_adjustment_audit_log_delete ON stock_adjustment_audit_log
                FOR DELETE USING (
                    current_setting('app.is_admin', true) = 'true'
                    OR branch_id = current_setting('app.branch_id', true)::integer
                )
        SQL);
        DB::statement(<<<'SQL'
            CREATE POLICY rls_stock_adjustment_audit_log_admin ON stock_adjustment_audit_log
                FOR ALL
                USING (current_setting('app.is_admin', true) = 'true')
                WITH CHECK (current_setting('app.is_admin', true) = 'true')
        SQL);

        // ── Register with pg_partman ──
        $this->registerPartman('stock_adjustment_audit_log', 'created_at', '2027-01-01');

        // ── Configure retention (3 years = 36 months) ──
        if ($this->hasPgPartman()) {
            DB::statement(<<<'SQL'
                UPDATE partman.part_config
                SET retention = '36 months',
                    retention_keep_table = true,
                    retention_schema = 'archive'
                WHERE parent_table = 'public.stock_adjustment_audit_log'
            SQL);
        }

        // ── Analyze ──
        DB::statement('ANALYZE stock_adjustment_audit_log');
    }

