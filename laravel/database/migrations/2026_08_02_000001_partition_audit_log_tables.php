/**
 * Phase 10.1 — Phase 1: Audit Log Partitioning (Lowest Risk).
 *
 * Partitions all 6 audit/log tables that have zero FK children.
 * These are append-only, high-growth tables that benefit most from
 * date-range partitioning and BRIN indexes.
 *
 * Tables (in order):
 *   1. financial_audit_log       — partition by created_at  (0 FK children, no RLS)
 *   2. user_audit_log            — partition by created_at  (0 FK children, no RLS)
 *   3. stock_take_audit_log      — partition by created_at  (0 FK children, RLS)
 *   4. stock_adjustment_audit_log— partition by created_at  (0 FK children, RLS)
 *   5. branch_demand_audit_log   — partition by created_at  (0 FK children, RLS)
 *   6. journal_posting_logs      — partition by performed_at (0 FK children, no RLS)
 *
 * DESIGN DECISIONS:
 *
 * 1. Partition key: All audit logs use RANGE by their timestamp column
 *    (created_at or performed_at) with monthly partitions. This enables:
 *    - Partition pruning for date-range queries
 *    - Easy archival of old months (DETACH PARTITION)
 *    - Faster VACUUM per partition
 *
 * 2. Composite PK: On partitioned tables, the PK must include the partition
 *    key. All tables change from PK(id) to PK(id, timestamp_column).
 *    GENERATED ALWAYS AS IDENTITY → GENERATED BY DEFAULT AS IDENTITY to
 *    allow OVERRIDING SYSTEM VALUE during data copy.
 *
 * 3. BRIN indexes: Replace B-tree indexes on the partition key column with
 *    BRIN indexes. Audit logs are append-only and naturally ordered by
 *    created_at, making BRIN 100-300x smaller and equally effective.
 *
 * 4. Outbound FKs: FKs FROM these tables TO other tables (e.g.
 *    stock_take_audit_log → stock_take_sessions) work normally on partitioned
 *    tables. They are included in the CREATE TABLE statement.
 *
 * 5. RLS: RLS policies defined on the parent table automatically apply to
 *    all partitions. We drop policies on the old table and recreate on the
 *    new partitioned parent.
 *
 * 6. financial_audit_log special handling:
 *    - Has cryptographic hash chain (prev_hash/row_hash). The trigger
 *      fn_financial_audit_trigger() inserts by name — works with partitioned
 *      table. We temporarily disable audit triggers on the 10 financial
 *      tables during the data copy to prevent hash-chain continuity issues.
 *    - Has REVOKE UPDATE/DELETE (immutable). Must be re-applied.
 *    - Has view v_financial_audit_chain_verification. Must be recreated.
 *
 * 7. journal_posting_logs FK → journal_entries(id):
 *    This is an outbound FK from a partitioned table to a non-partitioned
 *    table — fully supported. When journal_entries is later partitioned
 *    (Phase 6), this FK will need to be converted to trigger-based.
 *
 * MIGRATION STRATEGY (per table):
 *   a. Drop indexes on old table
 *   b. Drop RLS policies on old table (if any)
 *   c. Rename old table to _unpartitioned
 *   d. Create new partitioned table with composite PK + outbound FKs
 *   e. Create monthly partitions (2026-01 to 2026-12) + default partition
 *   f. Copy data from old table (OVERRIDING SYSTEM VALUE)
 *   g. Fix identity sequence
 *   h. Recreate indexes on parent (propagated to partitions)
 *   i. Recreate RLS policies on parent (if any)
 *   j. Re-apply REVOKE (for financial_audit_log)
 *   k. Drop old table
 *   l. Register with pg_partman
 *   m. Analyze
 *
 * ⚠️  This migration should be run during a maintenance window.
 *     It locks tables during the data copy phase.
 */
