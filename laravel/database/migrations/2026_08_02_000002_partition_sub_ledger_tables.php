            CREATE MATERIALIZED VIEW mv_ar_aging AS
            SELECT
                c.id AS customer_id,
                c.customer_code,
                c.customer_name,
                c.mobile,
                cl.branch_id,
                b.branch_name,
                SUM(CASE WHEN (CURRENT_DATE - cl.transaction_date) <= 30
                    THEN (cl.debit - cl.credit) ELSE 0 END) AS bucket_0_30,
