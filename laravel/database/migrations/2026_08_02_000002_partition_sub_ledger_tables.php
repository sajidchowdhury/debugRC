    private function partitionCustomerLedger(): void
    {
        if ($this->isAlreadyPartitioned('customer_ledger')) {
            return;
        }

        // ── Drop indexes on old table ──
        $this->dropIndexesExceptPK('customer_ledger');

        // ── Drop RLS policies on old table ──
        $this->dropRlsPolicies('customer_ledger');

        // ── Rename old table ──
        DB::statement(
            'ALTER TABLE customer_ledger RENAME TO customer_ledger_unpartitioned'
        );

        // ── Create partitioned table ──
        // PK must include partition key: (id, transaction_date)
        // GENERATED ALWAYS → GENERATED BY DEFAULT for OVERRIDING SYSTEM VALUE
        // Outbound FKs: customer_id → customers(id), journal_entry_id → journal_entries(id)
        // Both are DEFERRABLE INITIALLY DEFERRED (from migration 2025_01_21_000005)
        DB::statement(<<<'SQL'
            CREATE TABLE customer_ledger (
                id                INTEGER GENERATED BY DEFAULT AS IDENTITY,
                customer_id       INTEGER NOT NULL,
                branch_id         INTEGER,
                transaction_date  DATE NOT NULL,
                transaction_type  VARCHAR(30) NOT NULL,
                reference_type    VARCHAR(30),
                reference_id      INTEGER,
                debit             NUMERIC(14,2) DEFAULT 0,
                credit            NUMERIC(14,2) DEFAULT 0,
                balance           NUMERIC(14,2) DEFAULT 0,
                is_reversed       BOOLEAN NOT NULL DEFAULT false,
                reversed_at       TIMESTAMP(0),
                reversed_by       BIGINT,
                description       TEXT,
                journal_entry_id  INTEGER REFERENCES journal_entries(id) DEFERRABLE INITIALLY DEFERRED,
                created_by        INTEGER,
                created_at        TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY (id, transaction_date)
            ) PARTITION BY RANGE (transaction_date)
        SQL);

        // ── Create partitions ──
        $this->createPreYearPartition('customer_ledger', 'pre2026', '2026');
        $this->createMonthlyPartitions('customer_ledger', '2026');

        // ── Copy data ──
        DB::statement(<<<'SQL'
            INSERT INTO customer_ledger (
                id, customer_id, branch_id, transaction_date, transaction_type,
                reference_type, reference_id, debit, credit, balance,
                is_reversed, reversed_at, reversed_by, description,
                journal_entry_id, created_by, created_at
            )
            OVERRIDING SYSTEM VALUE
            SELECT
                id, customer_id, branch_id, transaction_date, transaction_type,
                reference_type, reference_id, debit, credit, balance,
                is_reversed, reversed_at, reversed_by, description,
                journal_entry_id, created_by, created_at
            FROM customer_ledger_unpartitioned
            ORDER BY transaction_date, id
        SQL);

        // ── Flush deferred FK triggers before creating indexes ──
        // DEFERRABLE INITIALLY DEFERRED constraints leave pending trigger events
        // after the INSERT, which blocks CREATE INDEX with:
        //   "cannot CREATE INDEX because it has pending trigger events"
        DB::statement('SET CONSTRAINTS ALL IMMEDIATE');

        // ── Fix sequence ──
        $this->fixSequence('customer_ledger');

        // ── Recreate indexes on parent (propagated to partitions) ──
        // Composite indexes for common query patterns
        DB::statement(
            'CREATE INDEX idx_cl_customer_date ON customer_ledger (customer_id, transaction_date)'
        );
        DB::statement(
            'CREATE INDEX idx_cl_reference ON customer_ledger (reference_type, reference_id)'
        );
        DB::statement(
            'CREATE INDEX idx_cl_branch ON customer_ledger (branch_id)'
        );
        DB::statement(
            'CREATE INDEX idx_cl_journal ON customer_ledger (journal_entry_id)'
        );
        DB::statement(
            'CREATE INDEX idx_cl_customer_branch ON customer_ledger (customer_id, branch_id)'
        );
        // Covering index for balance queries
        DB::statement(<<<'SQL'
            CREATE INDEX idx_cl_balance_covering
                ON customer_ledger (customer_id, is_reversed)
                INCLUDE (debit, credit)
        SQL);
        // Partial index for outstanding balances
        DB::statement(<<<'SQL'
            CREATE INDEX idx_cl_outstanding
                ON customer_ledger (customer_id, transaction_date, balance)
                WHERE balance > 0
        SQL);
        // BRIN index on partition key — replaces B-tree for append-only
        DB::statement(<<<'SQL'
            CREATE INDEX idx_cl_transaction_date_brin
                ON customer_ledger USING BRIN (transaction_date)
                WITH (pages_per_range = 32)
        SQL);
        // BRIN on created_at for time-range queries
        DB::statement(<<<'SQL'
            CREATE INDEX idx_cl_created_at_brin
                ON customer_ledger USING BRIN (created_at)
                WITH (pages_per_range = 32)
        SQL);

        // ── Recreate RLS policies ──
        DB::statement('ALTER TABLE customer_ledger ENABLE ROW LEVEL SECURITY');
        DB::statement('ALTER TABLE customer_ledger FORCE ROW LEVEL SECURITY');

        DB::statement(<<<'SQL'
            CREATE POLICY rls_customer_ledger_select ON customer_ledger
                FOR SELECT USING (
                    current_setting('app.is_admin', true) = 'true'
                    OR branch_id = current_setting('app.branch_id')::int
                )
