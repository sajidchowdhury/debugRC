use Illuminate\Database\Migrations\Migration;
use Illuminate\Support\Facades\DB;

/**
 * Phase 10.1 — Phase 2: Sub-Ledger Partitioning (Low Risk).
 *
 * Partitions all 5 sub-ledger tables by transaction_date (RANGE, monthly).
 * These are append-only, high-growth tables that benefit from date-range
 * partitioning and BRIN indexes.
 *
 * Tables (in order):
 *   1. customer_ledger   — partition by transaction_date (0 FK children, RLS)
 *   2. supplier_ledger   — partition by transaction_date (0 FK children, RLS)
 *   3. employee_ledger   — partition by transaction_date (0 FK children, RLS)
 *   4. cash_ledger       — partition by transaction_date (0 FK children, RLS)
 *   5. branch_ledger     — partition by transaction_date (0 FK children, RLS dual-branch)
 *
 * DESIGN DECISIONS:
 *
 * 1. Partition key: All sub-ledgers use RANGE by transaction_date with monthly
 *    partitions. This enables:
 *    - Partition pruning for aging report queries (WHERE transaction_date BETWEEN ...)
 *    - Easy archival of old months (DETACH PARTITION)
 *    - Faster VACUUM per partition
 *    - Partition-wise joins with journal_entries (Phase 6/7) when both use
 *      compatible date-based partitioning
 *
 * 2. Composite PK: On partitioned tables, the PK must include the partition
 *    key. All tables change from PK(id) to PK(id, transaction_date).
 *    GENERATED ALWAYS AS IDENTITY → GENERATED BY DEFAULT AS IDENTITY to
 *    allow OVERRIDING SYSTEM VALUE during data copy.
 *
 * 3. BRIN indexes: Replace B-tree indexes on transaction_date with BRIN.
 *    Sub-ledgers are append-only and naturally ordered by transaction_date,
 *    making BRIN 100-300x smaller and equally effective.
 *
 * 4. Outbound FKs: FKs FROM these tables TO other tables (e.g.
 *    customer_ledger.customer_id → customers(id)) work normally on partitioned
 *    tables. They are included in the CREATE TABLE statement.
 *    NOTE: customer_ledger.journal_entry_id → journal_entries(id) is a standard
 *    outbound FK. When journal_entries is later partitioned (Phase 6), this FK
 *    will need to be converted to trigger-based.
 *
 * 5. RLS: RLS policies defined on the parent table automatically apply to
 *    all partitions. We drop policies on the old table and recreate on the
 *    new partitioned parent.
 *    - customer_ledger, supplier_ledger, employee_ledger, cash_ledger:
 *      single branch_id column
 *    - branch_ledger: dual-branch (from_branch_id OR to_branch_id)
 *
 * 6. Materialized views: mv_ar_aging, mv_ap_aging, mv_branch_intercompany
 *    reference sub-ledger tables. PostgreSQL tracks column-level dependencies,
 *    so we must DROP + recreate these MVs after the table swap.
 *
 * 7. cash_ledger special handling:
 *    - Uses `amount` instead of `debit`/`credit`
 *    - branch_id is NOT NULL (other sub-ledgers have nullable branch_id)
 *    - No `is_reversed` column
 *    - No Eloquent model (accessed via DB::table() only)
 *
 * 8. branch_ledger special handling:
 *    - Dual-branch RLS (from_branch_id OR to_branch_id)
 *    - Uses `running_balance` instead of `balance`
 *    - Uses `remarks` instead of `description`
 *    - No Eloquent model (accessed via DB::table() only)
 *    - reference_type is varchar(50) not varchar(30)
 *
 * MIGRATION STRATEGY (per table):
 *   a. Drop materialized views that reference the table
 *   b. Drop indexes on old table
 *   c. Drop RLS policies on old table
 *   d. Rename old table to _unpartitioned
 *   e. Create new partitioned table with composite PK + outbound FKs
 *   f. Create monthly partitions (2026-01 to 2026-12) + default partition
 *   g. Copy data from old table (OVERRIDING SYSTEM VALUE)
 *   h. Fix identity sequence
 *   i. Recreate indexes on parent (propagated to partitions)
 *   j. Recreate RLS policies on parent
 *   k. Drop old table
 *   l. Register with pg_partman
 *   m. Recreate materialized views
 *   n. Analyze
 *
 * ⚠️  This migration should be run during a maintenance window.
 *     It locks tables during the data copy phase.
 */
return new class extends Migration
{
    private ?bool $hasPgPartman = null;

    // ── Helper methods ──────────────────────────────────────────────

    private function hasPgPartman(): bool
    {
        if ($this->hasPgPartman !== null) {
            return $this->hasPgPartman;
        }
        $row = DB::selectOne("
            SELECT EXISTS (
                SELECT 1 FROM pg_available_extensions WHERE name = 'pg_partman'
            ) AS installed
        ");
        $this->hasPgPartman = (bool) ($row->installed ?? false);
        if (! $this->hasPgPartman) {
            logger()->warning('pg_partman is not installed. Automatic partition maintenance is disabled.');
        }
        return $this->hasPgPartman;
    }

    private function isAlreadyPartitioned(string $tableName): bool
    {
        $row = DB::selectOne("
            SELECT 1
            FROM pg_partitioned_table pt
            JOIN pg_class c ON c.oid = pt.partrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE c.relname = ? AND n.nspname = current_schema()
            LIMIT 1
        ", [$tableName]);
        return $row !== null;
    }

    private function relationExists(string $name): bool
    {
        $row = DB::selectOne("
            SELECT 1
            FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE c.relname = ? AND n.nspname = current_schema()
            LIMIT 1
        ", [$name]);
        return $row !== null;
    }

    private function indexExists(string $indexName): bool
    {
        $row = DB::selectOne(
            "SELECT 1 FROM pg_indexes WHERE indexname = ? LIMIT 1",
            [$indexName]
        );
        return $row !== null;
    }

    /**
     * Create 12 monthly partitions for a given year + a default partition.
     * Idempotent — skips partitions that already exist.
     */
    private function createMonthlyPartitions(string $parent, string $year): void
    {
        for ($m = 1; $m <= 12; $m++) {
            $from = sprintf('%s-%02d-01', $year, $m);
            $to   = $m < 12
                ? sprintf('%s-%02d-01', $year, $m + 1)
                : sprintf('%d-01-01', (int) $year + 1);
            $name = sprintf('%s_%s_%02d', $parent, $year, $m);

            if (! $this->relationExists($name)) {
                DB::statement(
                    "CREATE TABLE {$name} PARTITION OF {$parent}
                     FOR VALUES FROM ('{$from}') TO ('{$to}')"
                );
            }
        }

        $defaultName = "{$parent}_default";
        if (! $this->relationExists($defaultName)) {
            DB::statement(
                "CREATE TABLE {$defaultName} PARTITION OF {$parent} DEFAULT"
            );
        }
    }

    /**
     * Create a pre-year catch-all partition for historical data.
     * Idempotent — skips if it already exists.
     */
    private function createPreYearPartition(string $parent, string $preYear, string $startYear): void
    {
        $name = "{$parent}_{$preYear}";
        if (! $this->relationExists($name)) {
            DB::statement(
                "CREATE TABLE {$name} PARTITION OF {$parent}
                 FOR VALUES FROM ('2020-01-01') TO ('{$startYear}-01-01')"
            );
        }
    }

    /**
     * Register a table with pg_partman for automatic monthly partition creation.
     * Wrapped in try/catch so re-runs don't fail if already registered.
     */
    private function registerPartman(string $parent, string $control, string $startPartition): void
    {
        if (! $this->hasPgPartman()) {
            return;
        }
        try {
            DB::statement(<<<SQL
                SELECT partman.create_parent(
                    p_parent_table    := 'public.{$parent}',
                    p_control         := '{$control}',
                    p_type            := 'range',
                    p_interval        := '1 month',
                    p_premake         := 6,
                    p_start_partition := '{$startPartition}'
                )
            SQL);
        } catch (\Throwable $e) {
            // Already registered with pg_partman — safe to ignore.
        }
    }

    /**
     * Fix the identity sequence after data copy.
     */
    private function fixSequence(string $table): void
    {
        DB::statement(<<<SQL
            SELECT setval(
                pg_get_serial_sequence('{$table}', 'id'),
                GREATEST(COALESCE((SELECT MAX(id) FROM {$table}), 0), 1)
            )
        SQL);
    }

    /**
     * Drop all RLS policies on a table. Used before renaming the old table.
     */
    private function dropRlsPolicies(string $tableName): void
    {
        $policies = DB::select("
            SELECT polname
            FROM pg_policy p
            JOIN pg_class c ON c.oid = p.polrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE c.relname = ? AND n.nspname = current_schema()
        ", [$tableName]);

        foreach ($policies as $policy) {
            DB::statement("DROP POLICY IF EXISTS {$policy->polname} ON {$tableName}");
        }
    }

    /**
     * Drop all indexes on a table (except the primary key).
     */
    private function dropIndexesExceptPK(string $tableName): void
    {
        $indexes = DB::select("
            SELECT indexname
            FROM pg_indexes
            WHERE tablename = ? AND indexname NOT LIKE '%_pkey'
        ", [$tableName]);

        foreach ($indexes as $idx) {
            DB::statement("DROP INDEX IF EXISTS {$idx->indexname}");
        }
    }

    // ── Main up() ───────────────────────────────────────────────────

    public function up(): void
    {
