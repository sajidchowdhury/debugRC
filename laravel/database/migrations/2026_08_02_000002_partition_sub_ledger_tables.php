    // ── Rollback ──────────────────────────────────────────────────

    /**
     * Rollback strategy: For each table, detach all partitions from the
     * partitioned parent, then create a new non-partitioned table and copy
     * all data back. This is the safest approach but requires enough disk
     * space to hold both copies temporarily.
     *
     * ⚠️  Rollback is expensive — run during a maintenance window.
     */
    public function down(): void
    {
        // ── Drop materialized views first ──
        $this->dropMaterializedViews();

        $this->rollbackCustomerLedger();
        $this->rollbackSupplierLedger();
        $this->rollbackEmployeeLedger();
        $this->rollbackCashLedger();
        $this->rollbackBranchLedger();

        // ── Recreate materialized views against non-partitioned tables ──
        $this->recreateMaterializedViews();
    }

    /**
     * Generic rollback helper: detach all partitions, create a flat table,
     * copy data, drop partitioned parent, rename flat table.
     */
    private function rollbackPartitionedTable(
        string $tableName,
        string $createFlatSQL,
        array $columns,
        array $indexDefinitions,
        array $rlsPolicyDefinitions
    ): void {
        // Check if the table is actually partitioned
        if (! $this->isAlreadyPartitioned($tableName)) {
            return;
        }

        $tempName = "{$tableName}_flat";

        // ── Detach all partitions ──
        $partitions = DB::select("
            SELECT c.relname
            FROM pg_inherits i
            JOIN pg_class c ON c.oid = i.inhrelid
            JOIN pg_class p ON p.oid = i.inhparent
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE p.relname = ? AND n.nspname = current_schema()
        ", [$tableName]);

        foreach ($partitions as $part) {
            DB::statement("ALTER TABLE {$tableName} DETACH PARTITION {$part->relname}");
        }

        // ── Create flat table with original PK(id) ──
        DB::statement($createFlatSQL);

        // ── Copy data from each partition ──
        $colList = implode(', ', $columns);
        foreach ($partitions as $part) {
            DB::statement(<<<SQL
                INSERT INTO {$tempName} ({$colList})
                OVERRIDING SYSTEM VALUE
                SELECT {$colList} FROM {$part->relname}
                ORDER BY id
            SQL);
        }
        // Also copy from the parent (in case data remains there)
        $parentCount = DB::selectOne("SELECT count(*) AS cnt FROM ONLY {$tableName}")->cnt;
        if ($parentCount > 0) {
            DB::statement(<<<SQL
                INSERT INTO {$tempName} ({$colList})
                OVERRIDING SYSTEM VALUE
                SELECT {$colList} FROM ONLY {$tableName}
                ORDER BY id
            SQL);
        }

        // ── Fix sequence ──
        $this->fixSequence($tempName);

        // ── Recreate indexes ──
        foreach ($indexDefinitions as $idxSQL) {
            DB::statement($idxSQL);
        }

        // ── Drop old partitioned parent and its detached partitions ──
        DB::statement("DROP TABLE {$tableName}");
        foreach ($partitions as $part) {
            DB::statement("DROP TABLE IF EXISTS {$part->relname}");
        }

        // ── Rename flat table to original name ──
        DB::statement("ALTER TABLE {$tempName} RENAME TO {$tableName}");

        // ── Recreate RLS policies ──
        DB::statement("ALTER TABLE {$tableName} ENABLE ROW LEVEL SECURITY");
        DB::statement("ALTER TABLE {$tableName} FORCE ROW LEVEL SECURITY");
        foreach ($rlsPolicyDefinitions as $policySQL) {
            DB::statement($policySQL);
        }

        // ── Analyze ──
        DB::statement("ANALYZE {$tableName}");
    }

