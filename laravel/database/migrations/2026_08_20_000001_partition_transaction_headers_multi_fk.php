        $this->dropAllFksToParent('stock_take_audit_log', 'stock_take_sessions');
        $this->createTriggerFkCheck(
            'stock_take_audit_log', 'stock_take_session_id', 'stock_take_sessions',
            'trg_fk_stal_sts_check', 'trg_stal_sts_fk_check'
        );
        $this->createTriggerFkCascadeDelete(
            'stock_take_audit_log', 'stock_take_session_id', 'stock_take_sessions',
            'trg_fk_sts_cascade_stal', 'trg_sts_cascade_stal'
        );

        // ── Partition stock_take_sessions ──
        $this->dropIndexesExceptPK('stock_take_sessions');
        $this->dropRlsPolicies('stock_take_sessions');

        DB::statement('ALTER TABLE stock_take_sessions RENAME TO stock_take_sessions_unpartitioned');

        DB::statement(<<<'SQL'
            CREATE TABLE stock_take_sessions (
                id                    INTEGER GENERATED BY DEFAULT AS IDENTITY,
                session_code          VARCHAR(30) NOT NULL,
                session_date          DATE NOT NULL,
                branch_id             INTEGER NOT NULL REFERENCES branches(id) DEFERRABLE INITIALLY DEFERRED,
                status                VARCHAR(20) NOT NULL DEFAULT 'draft'
                    CONSTRAINT stock_take_sessions_status_check
                    CHECK (status IN ('draft','counting','submitted','approved','posted','cancelled','reversed')),
                journal_entry_id      INTEGER REFERENCES journal_entries(id) DEFERRABLE INITIALLY DEFERRED,
                is_reversed           BOOLEAN NOT NULL DEFAULT false,
                reversed_at           TIMESTAMP(0),
                reversed_by           INTEGER,
                reverse_reason        TEXT,
                frozen_at             TIMESTAMP(0),
                freeze_outbound       BOOLEAN NOT NULL DEFAULT false,
                count_snapshot        JSONB,
                submitted_by          INTEGER,
                submitted_at          TIMESTAMP(0),
                approved_by           INTEGER,
                approved_at           TIMESTAMP(0),
                approval_comments     TEXT,
                count_scope           VARCHAR(20) NOT NULL DEFAULT 'full'
                    CONSTRAINT stock_take_sessions_count_scope_check
                    CHECK (count_scope IN ('full','category','abc','group','ad_hoc','negative_only','zero_only')),
                count_scope_payload   JSONB,
                re_open_count         INTEGER NOT NULL DEFAULT 0,
                last_reopened_at      TIMESTAMP(0),
                last_reopened_by      INTEGER REFERENCES users(id) ON DELETE SET NULL,
                reversal_of_entry_id  INTEGER REFERENCES journal_entries(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
                notes                 TEXT,
                created_by            INTEGER,
                created_at            TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP,
                updated_at            TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP,
                deleted_at            TIMESTAMP(0),
                PRIMARY KEY (id, session_date),
                CONSTRAINT stock_take_session_code_unique UNIQUE (session_code, session_date)
            ) PARTITION BY RANGE (session_date)
        SQL);

        $this->createPreYearPartition('stock_take_sessions', 'pre2026', '2026');
        $this->createMonthlyPartitions('stock_take_sessions', '2026');

        DB::statement(<<<'SQL'
            INSERT INTO stock_take_sessions (
                id, session_code, session_date, branch_id, status,
                journal_entry_id, is_reversed, reversed_at, reversed_by, reverse_reason,
                frozen_at, freeze_outbound, count_snapshot,
                submitted_by, submitted_at, approved_by, approved_at, approval_comments,
                count_scope, count_scope_payload,
                re_open_count, last_reopened_at, last_reopened_by, reversal_of_entry_id,
                notes, created_by, created_at, updated_at, deleted_at
            )
            OVERRIDING SYSTEM VALUE
            SELECT
                id, session_code, session_date, branch_id, status,
                journal_entry_id, is_reversed, reversed_at, reversed_by, reverse_reason,
                frozen_at, freeze_outbound, count_snapshot,
                submitted_by, submitted_at, approved_by, approved_at, approval_comments,
                count_scope, count_scope_payload,
                re_open_count, last_reopened_at, last_reopened_by, reversal_of_entry_id,
                notes, created_by, created_at, updated_at, deleted_at
            FROM stock_take_sessions_unpartitioned
            ORDER BY session_date, id
        SQL);

        DB::statement('SET CONSTRAINTS ALL IMMEDIATE');

        $this->fixSequence('stock_take_sessions');

        // Recreate indexes
        DB::statement('CREATE INDEX idx_sts_branch ON stock_take_sessions (branch_id)');
        DB::statement('CREATE INDEX idx_sts_is_reversed ON stock_take_sessions (is_reversed) WHERE is_reversed = true');
        DB::statement('CREATE INDEX idx_sts_reversed ON stock_take_sessions (branch_id, reversed_at) WHERE status = \'reversed\'');
        DB::statement('CREATE INDEX idx_sts_freeze_outbound ON stock_take_sessions (branch_id) WHERE freeze_outbound = true');
        DB::statement('CREATE INDEX idx_sts_submitted ON stock_take_sessions (branch_id, submitted_at) WHERE status = \'submitted\'');
        DB::statement(<<<'SQL'
            CREATE INDEX idx_sts_session_date_brin
                ON stock_take_sessions USING BRIN (session_date)
                WITH (pages_per_range = 32)
        SQL);

        // Recreate updated_at trigger
        DB::statement(<<<'SQL'
            CREATE TRIGGER trg_stock_take_sessions_updated_at
                BEFORE UPDATE ON stock_take_sessions
                FOR EACH ROW EXECUTE FUNCTION update_updated_at_column()
        SQL);

        $this->enableSingleBranchRls('stock_take_sessions');

        DB::statement('DROP TABLE stock_take_sessions_unpartitioned');
        $this->registerPartman('stock_take_sessions', 'session_date', '2027-01-01');
        DB::statement('ANALYZE stock_take_sessions');
    }

    // ═══════════════════════════════════════════════════════════════
    //  down() — rollback is manual (trigger-based FK reversal is complex)
    // ═══════════════════════════════════════════════════════════════

    public function down(): void
    {
        // Rollback of a partitioned-+-trigger-based-FK migration is non-trivial:
        //   1. Re-create the declarative FK on each child (requires data integrity check).
        //   2. Detach all partitions, copy data back to a flat table, drop partitioned parent.
        //   3. Rename flat table back, re-create all indexes/triggers/RLS policies.
        //
        // Per the Phase 4 migration's precedent (which leaves Group B rollbacks as
        // manual operations), we document the rollback procedure but do not
        // implement an automated one. Restoring from a pre-migration DB snapshot
        // is the recommended rollback path.
        Log::warning(
            'Phase 5 rollback: automated down() is intentionally a no-op. '
            . 'Restoring from a pre-migration DB snapshot is the recommended rollback path. '
            . 'Manual rollback requires: (1) re-creating declarative FKs on 11 child tables, '
            . '(2) detaching all partitions, (3) copying data back to flat tables, '
            . '(4) re-creating indexes/triggers/RLS policies per the original schema.'
        );
    }
