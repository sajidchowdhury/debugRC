<?php

use Illuminate\Database\Migrations\Migration;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;

/**
 * Phase 10.1 — Phase 5: Multi-FK Transaction Header Partitioning.
 *
 * Partitions 6 transaction header tables by their natural date column:
 *
 *   1. customer_payments     — by payment_date     (children: invoice_payment_allocations,
 *                                                   branch_demand_customer_payment_settlements)
 *   2. supplier_payments     — by payment_date     (child:  supplier_payment_settlements)
 *   3. sales_challans        — by challan_date     (child:  sales_challan_items)
 *   4. warehouse_transfers   — by transfer_date    (children: warehouse_transfer_items,
 *                                                   branch_demands)
 *   5. stock_adjustments     — by adjustment_date  (children: stock_adjustment_items,
 *                                                   stock_adjustment_audit_log)
 *   6. stock_take_sessions   — by session_date     (children: stock_take_warehouses,
 *                                                   stock_take_items,
 *                                                   stock_take_audit_log)
 *
 * 11 child-table FK conversions to trigger-based (revised from original plan's 8 —
 * see roadmap §4.1.1 for the schema-audit findings that revealed the extra 3):
 *
 *   - invoice_payment_allocations.payment_id                       → customer_payments(id) CASCADE
 *   - branch_demand_customer_payment_settlements.payment_id        → customer_payments(id) CASCADE
 *   - supplier_payment_settlements.payment_id                      → supplier_payments(id)   CASCADE
 *   - sales_challan_items.sales_challan_id                         → sales_challans(id)      CASCADE
 *   - warehouse_transfer_items.warehouse_transfer_id               → warehouse_transfers(id) CASCADE
 *   - branch_demands.warehouse_transfer_id                         → warehouse_transfers(id) SET NULL
 *   - stock_adjustment_items.stock_adjustment_id                   → stock_adjustments(id)   CASCADE
 *   - stock_adjustment_audit_log.stock_adjustment_id               → stock_adjustments(id)   CASCADE
 *   - stock_take_warehouses.stock_take_session_id                  → stock_take_sessions(id) CASCADE
 *   - stock_take_items.stock_take_session_id                       → stock_take_sessions(id) CASCADE
 *   - stock_take_audit_log.stock_take_session_id                   → stock_take_sessions(id) CASCADE
 *
 * Each FK conversion follows the Phase 4 pattern:
 *   1. Look up the declarative FK constraint name from pg_constraint.
 *   2. Drop the declarative FK.
 *   3. Create a BEFORE INSERT OR UPDATE check trigger on the child table.
 *   4. If ON DELETE CASCADE, create an AFTER DELETE cascade trigger on the parent.
 *   5. If ON DELETE SET NULL, create an AFTER DELETE set-null trigger on the parent.
 *
 * DESIGN NOTES
 * ------------
 * - PK(id) → PK(id, date_column) for partitioned parents (PostgreSQL requirement).
 * - GENERATED ALWAYS → GENERATED BY DEFAULT for OVERRIDING SYSTEM VALUE data copy.
 * - UNIQUE(code) → UNIQUE(code, date_column) — PostgreSQL requires the partition key
 *   in every UNIQUE constraint on a partitioned table.
 * - Declarative FKs to journal_entries(id) are PRESERVED (Phase 6 converts them).
 * - sales_challans.sales_invoice_id is already trigger-based (trg_fk_sc_si) — preserved.
 * - stock_adjustment_items.sai_stock_tx_fk is a composite declarative FK to
 *   stock_transactions(id, transaction_date) — preserved (out of scope for Phase 5).
 * - All 6 parents: deleted_at (soft deletes), created_at/updated_at, branch_id (RLS).
 *   warehouse_transfers uses dual-branch RLS (from_branch_id OR to_branch_id).
 * - Triggers preserved on parents: updated_at, financial_audit (customer_payments +
 *   supplier_payments only), LISTEN/NOTIFY (customer_payments + sales_challans),
 *   trg_fk_sc_si (sales_challans only), trg_enforce_same_branch_transfer
 *   (warehouse_transfers only).
 *
 * IDEMPOTENT: each partition method early-returns if the table is already partitioned.
 *
 * ⚠️  Run during a maintenance window — locks tables during the data copy phase.
 */
return new class extends Migration
{
    private ?bool $hasPgPartman = null;

    // ═══════════════════════════════════════════════════════════════
    //  Helpers (same patterns as Phase 4 migration)
    // ═══════════════════════════════════════════════════════════════

    private function hasPgPartman(): bool
    {
        if ($this->hasPgPartman !== null) {
            return $this->hasPgPartman;
        }
        $row = DB::selectOne("
            SELECT EXISTS (
                SELECT 1 FROM pg_available_extensions WHERE name = 'pg_partman'
            ) AS installed
        ");
        $this->hasPgPartman = (bool) ($row->installed ?? false);
        if (! $this->hasPgPartman) {
            logger()->warning('pg_partman is not installed. Automatic partition maintenance is disabled.');
        }
        return $this->hasPgPartman;
    }

    private function isAlreadyPartitioned(string $tableName): bool
    {
        $row = DB::selectOne("
            SELECT 1
            FROM pg_partitioned_table pt
            JOIN pg_class c ON c.oid = pt.partrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE c.relname = ? AND n.nspname = current_schema()
            LIMIT 1
        ", [$tableName]);
        return $row !== null;
    }

    private function relationExists(string $name): bool
    {
        $row = DB::selectOne("
            SELECT 1
            FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE c.relname = ? AND n.nspname = current_schema()
            LIMIT 1
        ", [$name]);
        return $row !== null;
    }

    private function createMonthlyPartitions(string $parent, string $year): void
    {
        for ($m = 1; $m <= 12; $m++) {
            $from = sprintf('%s-%02d-01', $year, $m);
            $to   = $m < 12
                ? sprintf('%s-%02d-01', $year, $m + 1)
                : sprintf('%d-01-01', (int) $year + 1);
            $name = sprintf('%s_%s_%02d', $parent, $year, $m);

            if (! $this->relationExists($name)) {
                DB::statement(
                    "CREATE TABLE {$name} PARTITION OF {$parent}
                     FOR VALUES FROM ('{$from}') TO ('{$to}')"
                );
            }
        }

        $defaultName = "{$parent}_default";
        if (! $this->relationExists($defaultName)) {
            DB::statement(
                "CREATE TABLE {$defaultName} PARTITION OF {$parent} DEFAULT"
            );
        }
    }

    private function createPreYearPartition(string $parent, string $preYear, string $startYear): void
    {
        $name = "{$parent}_{$preYear}";
        if (! $this->relationExists($name)) {
            DB::statement(
                "CREATE TABLE {$name} PARTITION OF {$parent}
                 FOR VALUES FROM ('2020-01-01') TO ('{$startYear}-01-01')"
            );
        }
    }

    private function registerPartman(string $parent, string $control, string $startPartition): void
    {
        if (! $this->hasPgPartman()) {
            return;
        }
        try {
            DB::statement(<<<SQL
                SELECT partman.create_parent(
                    p_parent_table    := 'public.{$parent}',
                    p_control         := '{$control}',
                    p_type            := 'range',
                    p_interval        := '1 month',
                    p_premake         := 6,
                    p_start_partition := '{$startPartition}'
                )
            SQL);
        } catch (\Throwable $e) {
            // Already registered with pg_partman — safe to ignore.
        }
    }

    private function fixSequence(string $table): void
    {
        DB::statement(<<<SQL
            SELECT setval(
                pg_get_serial_sequence('{$table}', 'id'),
                GREATEST(COALESCE((SELECT MAX(id) FROM {$table}), 0), 1)
            )
        SQL);
    }

    private function dropRlsPolicies(string $tableName): void
    {
        $policies = DB::select("
            SELECT polname
            FROM pg_policy p
            JOIN pg_class c ON c.oid = p.polrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE c.relname = ? AND n.nspname = current_schema()
        ", [$tableName]);

        foreach ($policies as $policy) {
            DB::statement("DROP POLICY IF EXISTS {$policy->polname} ON {$tableName}");
        }
    }

    private function dropIndexesExceptPK(string $tableName): void
    {
        $indexes = DB::select("
            SELECT indexname
            FROM pg_indexes
            WHERE tablename = ? AND indexname NOT LIKE '%_pkey'
        ", [$tableName]);

        foreach ($indexes as $idx) {
            DB::statement("DROP INDEX IF EXISTS {$idx->indexname}");
        }
    }

    /**
     * Drop a declarative FK constraint by table + constraint name.
     */
    private function dropFkConstraint(string $table, string $constraintName): void
    {
        DB::statement("ALTER TABLE {$table} DROP CONSTRAINT IF EXISTS {$constraintName}");
    }

    /**
     * Drop ALL declarative FKs from a child table to a given parent.
     * Used when the constraint name is auto-generated (not known ahead of time).
     * Returns the list of (constraint_name, fk_column, on_delete) that were dropped.
     *
     * @return list<array{conname: string, col: string, deltype: string}>
     */
    private function dropAllFksToParent(string $childTable, string $parentTable): array
    {
        $fks = DB::select(<<<SQL
            SELECT c.conname, a.attname AS col, c.confdeltype AS deltype
            FROM pg_constraint c
            JOIN pg_class t ON t.oid = c.conrelid
            JOIN pg_namespace n ON n.oid = t.relnamespace
            JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY(c.conkey)
            JOIN pg_class rt ON rt.oid = c.confrelid
            JOIN pg_namespace rn ON rn.oid = rt.relnamespace
            WHERE t.relname = ?
              AND n.nspname = 'public'
              AND c.contype = 'f'
              AND rt.relname = ?
              AND rn.nspname = 'public'
        SQL, [$childTable, $parentTable]);

        $dropped = [];
        foreach ($fks as $fk) {
            DB::statement("ALTER TABLE {$childTable} DROP CONSTRAINT IF EXISTS {$fk->conname}");
            $dropped[] = ['conname' => $fk->conname, 'col' => $fk->col, 'deltype' => $fk->deltype];
            Log::info("Phase 5: Dropped declarative FK {$fk->conname} on {$childTable}.{$fk->col} → {$parentTable}(id)");
        }
        return $dropped;
    }

    /**
     * Create a trigger-based FK check function + trigger for a child→parent reference.
     * Replaces declarative FK when the parent is partitioned.
     */
    private function createTriggerFkCheck(
        string $childTable,
        string $fkColumn,
        string $parentTable,
        string $triggerFuncName,
        string $triggerName
    ): void {
        DB::statement("DROP TRIGGER IF EXISTS {$triggerName} ON {$childTable}");

        DB::statement(<<<SQL
            CREATE OR REPLACE FUNCTION {$triggerFuncName}()
            RETURNS TRIGGER AS \$\$
            BEGIN
                IF NEW.{$fkColumn} IS NOT NULL THEN
                    IF NOT EXISTS (
                        SELECT 1 FROM {$parentTable}
                        WHERE id = NEW.{$fkColumn}
                    ) THEN
                        RAISE EXCEPTION 'FK violation: {$parentTable}(id=%) not found for {$childTable}.{$fkColumn}',
                            NEW.{$fkColumn};
                    END IF;
                END IF;
                RETURN NEW;
            END;
            \$\$ LANGUAGE plpgsql
        SQL);

        DB::statement(<<<SQL
            CREATE TRIGGER {$triggerName}
                BEFORE INSERT OR UPDATE OF {$fkColumn} ON {$childTable}
                FOR EACH ROW EXECUTE FUNCTION {$triggerFuncName}()
        SQL);
    }

    /**
     * Create a trigger-based cascade delete function + trigger on the parent.
     */
    private function createTriggerFkCascadeDelete(
        string $childTable,
        string $fkColumn,
        string $parentTable,
        string $triggerFuncName,
        string $triggerName
    ): void {
        DB::statement("DROP TRIGGER IF EXISTS {$triggerName} ON {$parentTable}");

        DB::statement(<<<SQL
            CREATE OR REPLACE FUNCTION {$triggerFuncName}()
            RETURNS TRIGGER AS \$\$
            BEGIN
                DELETE FROM {$childTable} WHERE {$fkColumn} = OLD.id;
                RETURN OLD;
            END;
            \$\$ LANGUAGE plpgsql
        SQL);

        DB::statement(<<<SQL
            CREATE TRIGGER {$triggerName}
                AFTER DELETE ON {$parentTable}
                FOR EACH ROW EXECUTE FUNCTION {$triggerFuncName}()
        SQL);
    }

    /**
     * Create a trigger-based SET NULL function + trigger on the parent.
     */
    private function createTriggerFkSetNull(
        string $childTable,
        string $fkColumn,
        string $parentTable,
        string $triggerFuncName,
        string $triggerName
    ): void {
        DB::statement("DROP TRIGGER IF EXISTS {$triggerName} ON {$parentTable}");

        DB::statement(<<<SQL
            CREATE OR REPLACE FUNCTION {$triggerFuncName}()
            RETURNS TRIGGER AS \$\$
            BEGIN
                UPDATE {$childTable} SET {$fkColumn} = NULL WHERE {$fkColumn} = OLD.id;
                RETURN OLD;
            END;
            \$\$ LANGUAGE plpgsql
        SQL);

        DB::statement(<<<SQL
            CREATE TRIGGER {$triggerName}
                AFTER DELETE ON {$parentTable}
                FOR EACH ROW EXECUTE FUNCTION {$triggerFuncName}()
        SQL);
    }

    /**
     * Re-enable single-branch RLS with the standard 5-policy pattern.
     */
    private function enableSingleBranchRls(string $table): void
    {
        DB::statement("ALTER TABLE {$table} ENABLE ROW LEVEL SECURITY");
        DB::statement("ALTER TABLE {$table} FORCE ROW LEVEL SECURITY");

        $cond = "current_setting('app.is_admin', true) = 'true' OR branch_id = current_setting('app.branch_id')::int";
        DB::statement("CREATE POLICY rls_{$table}_select ON {$table} FOR SELECT USING ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_insert ON {$table} FOR INSERT WITH CHECK ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_update ON {$table} FOR UPDATE USING ({$cond}) WITH CHECK ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_delete ON {$table} FOR DELETE USING ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_admin ON {$table} FOR ALL USING (current_setting('app.is_admin', true) = 'true') WITH CHECK (current_setting('app.is_admin', true) = 'true')");
    }

    /**
     * Re-enable dual-branch RLS (from_branch_id OR to_branch_id) — used by warehouse_transfers.
     */
    private function enableDualBranchRls(string $table): void
    {
        DB::statement("ALTER TABLE {$table} ENABLE ROW LEVEL SECURITY");
        DB::statement("ALTER TABLE {$table} FORCE ROW LEVEL SECURITY");

        $cond = "current_setting('app.is_admin', true) = 'true' OR from_branch_id = current_setting('app.branch_id')::int OR to_branch_id = current_setting('app.branch_id')::int";
        DB::statement("CREATE POLICY rls_{$table}_select ON {$table} FOR SELECT USING ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_insert ON {$table} FOR INSERT WITH CHECK ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_update ON {$table} FOR UPDATE USING ({$cond}) WITH CHECK ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_delete ON {$table} FOR DELETE USING ({$cond})");
        DB::statement("CREATE POLICY rls_{$table}_admin ON {$table} FOR ALL USING (current_setting('app.is_admin', true) = 'true') WITH CHECK (current_setting('app.is_admin', true) = 'true')");
    }

    // ═══════════════════════════════════════════════════════════════
    //  up()
    // ═══════════════════════════════════════════════════════════════

    public function up(): void
    {
        if ($this->hasPgPartman()) {
            DB::statement('CREATE EXTENSION IF NOT EXISTS pg_partman');
            DB::statement('CREATE SCHEMA IF NOT EXISTS partman');
        }

        $this->partitionCustomerPayments();
        $this->partitionSupplierPayments();
        $this->partitionSalesChallans();
        $this->partitionWarehouseTransfers();
        $this->partitionStockAdjustments();
        $this->partitionStockTakeSessions();
    }

    // ═══════════════════════════════════════════════════════════════
    //  1. customer_payments  (children: invoice_payment_allocations,
    //                                  branch_demand_customer_payment_settlements)
    // ═══════════════════════════════════════════════════════════════

    private function partitionCustomerPayments(): void
    {
        if ($this->isAlreadyPartitioned('customer_payments')) {
            return;
        }

        // ── Convert inbound FKs to trigger-based BEFORE partitioning ──
        // 1. invoice_payment_allocations.payment_id → customer_payments(id) ON DELETE CASCADE
        $this->dropFkConstraint('invoice_payment_allocations', 'ipa_payment_id_foreign');
        $this->createTriggerFkCheck(
            'invoice_payment_allocations', 'payment_id', 'customer_payments',
            'trg_fk_ipa_cp_check', 'trg_ipa_cp_fk_check'
        );
        $this->createTriggerFkCascadeDelete(
            'invoice_payment_allocations', 'payment_id', 'customer_payments',
            'trg_fk_cp_cascade_ipa', 'trg_cp_cascade_ipa'
        );

        // 2. branch_demand_customer_payment_settlements.payment_id → customer_payments(id) ON DELETE CASCADE
        //    FK is inline-auto-named — discover + drop all FKs to this parent.
        $this->dropAllFksToParent('branch_demand_customer_payment_settlements', 'customer_payments');
        $this->createTriggerFkCheck(
            'branch_demand_customer_payment_settlements', 'payment_id', 'customer_payments',
            'trg_fk_bdcpss_cp_check', 'trg_bdcpss_cp_fk_check'
        );
        $this->createTriggerFkCascadeDelete(
            'branch_demand_customer_payment_settlements', 'payment_id', 'customer_payments',
            'trg_fk_cp_cascade_bdcpss', 'trg_cp_cascade_bdcpss'
        );

        // ── Partition customer_payments ──
        $this->dropIndexesExceptPK('customer_payments');
        $this->dropRlsPolicies('customer_payments');

        DB::statement('ALTER TABLE customer_payments RENAME TO customer_payments_unpartitioned');

        DB::statement(<<<'SQL'
            CREATE TABLE customer_payments (
                id                            INTEGER GENERATED BY DEFAULT AS IDENTITY,
                payment_code                  VARCHAR(30) NOT NULL,
                payment_date                  DATE NOT NULL,
                customer_id                   INTEGER NOT NULL,
                branch_id                     INTEGER NOT NULL REFERENCES branches(id) DEFERRABLE INITIALLY DEFERRED,
                bank_id                       INTEGER REFERENCES banks(id) DEFERRABLE INITIALLY DEFERRED,
                collected_by                  INTEGER,
                payment_mode                  VARCHAR(20) NOT NULL CHECK (payment_mode IN ('cash','bank','mobile_banking','cheque','adjustment')),
                transaction_type              VARCHAR(20) NOT NULL DEFAULT 'receive' CHECK (transaction_type IN ('receive','payment','discount','write_off')),
                reference_no                  VARCHAR(100),
                amount                        NUMERIC(14,2) NOT NULL DEFAULT 0,
                discount_amount               NUMERIC(14,2) DEFAULT 0,
                journal_entry_id              INTEGER REFERENCES journal_entries(id) DEFERRABLE INITIALLY DEFERRED,
                intercompany_journal_entry_id INTEGER REFERENCES journal_entries(id) DEFERRABLE INITIALLY DEFERRED,
                is_reversed                   BOOLEAN NOT NULL DEFAULT false,
                reversed_at                   TIMESTAMP(0),
                reversed_by                   INTEGER,
                reverse_reason                TEXT,
                notes                         TEXT,
                created_by                    INTEGER,
                created_at                    TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP,
                updated_at                    TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP,
                deleted_at                    TIMESTAMP(0),
                PRIMARY KEY (id, payment_date),
                CONSTRAINT customer_payments_code_unique UNIQUE (payment_code, payment_date)
            ) PARTITION BY RANGE (payment_date)
        SQL);

        $this->createPreYearPartition('customer_payments', 'pre2026', '2026');
        $this->createMonthlyPartitions('customer_payments', '2026');

        DB::statement(<<<'SQL'
            INSERT INTO customer_payments (
                id, payment_code, payment_date, customer_id, branch_id,
                bank_id, collected_by, payment_mode, transaction_type, reference_no,
                amount, discount_amount, journal_entry_id, intercompany_journal_entry_id,
                is_reversed, reversed_at, reversed_by, reverse_reason,
                notes, created_by, created_at, updated_at, deleted_at
            )
            OVERRIDING SYSTEM VALUE
            SELECT
                id, payment_code, payment_date, customer_id, branch_id,
                bank_id, collected_by, payment_mode, transaction_type, reference_no,
                amount, discount_amount, journal_entry_id, intercompany_journal_entry_id,
                is_reversed, reversed_at, reversed_by, reverse_reason,
                notes, created_by, created_at, updated_at, deleted_at
            FROM customer_payments_unpartitioned
            ORDER BY payment_date, id
        SQL);

        DB::statement('SET CONSTRAINTS ALL IMMEDIATE');

        $this->fixSequence('customer_payments');

        // Recreate indexes
        DB::statement('CREATE INDEX idx_cp_customer ON customer_payments (customer_id)');
        DB::statement('CREATE INDEX idx_cp_bank ON customer_payments (bank_id)');
        DB::statement('CREATE INDEX idx_cp_branch ON customer_payments (branch_id)');
        DB::statement('CREATE INDEX idx_cp_journal ON customer_payments (journal_entry_id)');
        DB::statement('CREATE INDEX idx_cp_reference_no ON customer_payments (reference_no) WHERE reference_no IS NOT NULL');
        DB::statement('CREATE INDEX idx_cp_active ON customer_payments (customer_id, payment_date) WHERE is_reversed = false');
        DB::statement('CREATE INDEX idx_cp_active_by_branch ON customer_payments (branch_id, payment_date) WHERE is_reversed = false');
        DB::statement(<<<'SQL'
            CREATE INDEX idx_cp_listing_covering ON customer_payments (branch_id, payment_date DESC, id DESC)
                INCLUDE (customer_id, payment_code, payment_mode, amount, is_reversed)
        SQL);
        DB::statement('CREATE INDEX idx_cp_perf_user_date ON customer_payments (created_by, payment_date) WHERE is_reversed = false');
        DB::statement(<<<'SQL'
            CREATE INDEX idx_cp_payment_date_brin
                ON customer_payments USING BRIN (payment_date)
                WITH (pages_per_range = 32)
        SQL);
        DB::statement(<<<'SQL'
            CREATE INDEX idx_cp_created_at_brin
                ON customer_payments USING BRIN (created_at)
                WITH (pages_per_range = 32)
        SQL);

        // Recreate updated_at trigger (function exists globally)
        DB::statement(<<<'SQL'
            CREATE TRIGGER trg_customer_payments_updated_at
                BEFORE UPDATE ON customer_payments
                FOR EACH ROW EXECUTE FUNCTION update_updated_at_column()
        SQL);

        // Recreate LISTEN/NOTIFY trigger (function rcerp_notify_customer_payment exists)
        DB::statement(<<<'SQL'
            CREATE TRIGGER trg_notify_customer_payments
                AFTER INSERT OR UPDATE ON customer_payments
                FOR EACH ROW EXECUTE FUNCTION rcerp_notify_customer_payment()
        SQL);

        // Recreate financial audit trigger (function fn_financial_audit_trigger exists)
        DB::statement(<<<'SQL'
            CREATE TRIGGER trg_audit_customer_payments
                AFTER INSERT OR UPDATE OR DELETE ON customer_payments
                FOR EACH ROW EXECUTE FUNCTION fn_financial_audit_trigger()
        SQL);

        $this->enableSingleBranchRls('customer_payments');

        DB::statement('DROP TABLE customer_payments_unpartitioned');
        $this->registerPartman('customer_payments', 'payment_date', '2027-01-01');
        DB::statement('ANALYZE customer_payments');
    }

    // ═══════════════════════════════════════════════════════════════
    //  2. supplier_payments  (child: supplier_payment_settlements)
    // ═══════════════════════════════════════════════════════════════

    private function partitionSupplierPayments(): void
    {
        if ($this->isAlreadyPartitioned('supplier_payments')) {
            return;
        }

        // ── Convert inbound FK to trigger-based ──
        // supplier_payment_settlements.payment_id → supplier_payments(id) ON DELETE CASCADE (auto-named)
        $this->dropAllFksToParent('supplier_payment_settlements', 'supplier_payments');
        $this->createTriggerFkCheck(
            'supplier_payment_settlements', 'payment_id', 'supplier_payments',
            'trg_fk_sps_sp_check', 'trg_sps_sp_fk_check'
        );
        $this->createTriggerFkCascadeDelete(
            'supplier_payment_settlements', 'payment_id', 'supplier_payments',
            'trg_fk_sp_cascade_sps', 'trg_sp_cascade_sps'
        );

        // ── Partition supplier_payments ──
        $this->dropIndexesExceptPK('supplier_payments');
        $this->dropRlsPolicies('supplier_payments');

        DB::statement('ALTER TABLE supplier_payments RENAME TO supplier_payments_unpartitioned');

        DB::statement(<<<'SQL'
            CREATE TABLE supplier_payments (
                id                            INTEGER GENERATED BY DEFAULT AS IDENTITY,
                payment_code                  VARCHAR(30) NOT NULL,
                payment_date                  DATE NOT NULL,
                supplier_id                   INTEGER NOT NULL REFERENCES suppliers(id) DEFERRABLE INITIALLY DEFERRED,
                branch_id                     INTEGER NOT NULL REFERENCES branches(id) DEFERRABLE INITIALLY DEFERRED,
                bank_id                       INTEGER REFERENCES banks(id) DEFERRABLE INITIALLY DEFERRED,
                payment_mode                  VARCHAR(20) NOT NULL CHECK (payment_mode IN ('cash','bank','mobile_banking','cheque','adjustment')),
                transaction_type              VARCHAR(20) NOT NULL DEFAULT 'payment'
                    CONSTRAINT supplier_payments_transaction_type_check
