use Tests\TestCase;

/**
 * Phase 19 (Task 19-RATELIMIT-PRINT) — Print view feature tests.
 *
 * Covers the 9 master-data modules that expose a print-friendly directory
 * view via BaseMasterDataController::print():
 *
 *   GET /admin/branches/print    (admin, manager, warehouse_manager)
 *   GET /admin/warehouses/print  (admin, manager, warehouse_manager)
 *   GET /admin/products/print    (admin, manager, warehouse_manager)
 *   GET /admin/customers/print   (admin, manager, salesman)
 *   GET /admin/suppliers/print    (admin, manager, accountant)
 *   GET /admin/employees/print    (admin, manager, hr)
 *   GET /admin/banks/print        (admin, manager, accountant)
 *   GET /admin/users/print        (admin, manager)
 *   GET /admin/ledgers/print      (admin, accountant)
 *
 * Each test verifies:
 *   - The route returns 200 + text/html Content-Type.
 *   - The view is the module's print.blade.php extending the shared layout.
 *   - Table headers (from printColumns()) are present.
 *   - At least one data row is rendered for seeded records.
 *   - The "Print" button (window.print() trigger) is present in the toolbar.
 *
 * Auth + RBAC tests:
 *   - Unauthenticated → redirect to login.
 *   - Salesman (denied on branches) → redirect to dashboard.
 */
class PrintViewTest extends TestCase
{
    use BuildsRoleUsers, InsertsBankDependencies;

    // ====================================================================
    // SHARED ASSERTIONS
    // ====================================================================

    /**
     * Assert the response looks like a print HTML page: 200, text/html,
     * contains the shared print-layout markers + Print button.
     */
    private function assertPrintResponse($response, string $moduleName, array $expectedHeaders = []): string
    {
        $response->assertOk();
        $response->assertHeader('Content-Type', 'text/html; charset=UTF-8');

        $body = $response->getContent();
        $this->assertNotEmpty($body, "Print page body for {$moduleName} is empty.");

        // The shared layout's print button (window.print trigger).
        $this->assertStringContainsString('window.print()', $body, "Print button missing for {$moduleName}.");

        // The shared layout's footer signature.
        $this->assertStringContainsString('Generated by', $body, "Footer missing for {$moduleName}.");
        $this->assertStringContainsString('RC ERP', $body, "RC ERP signature missing for {$moduleName}.");

        // @media print CSS rule must be present.
        $this->assertStringContainsString('@media print', $body, "@media print CSS missing for {$moduleName}.");

        // Each expected header label should appear in the table head.
        foreach ($expectedHeaders as $header) {
            $this->assertStringContainsString(
                '>' . $header . '<',
                $body,
                "Header '{$header}' not found in print view for {$moduleName}.",
            );
        }

        return $body;
    }

    /**
     * Assert the response body contains at least one row of data (excluding
     * the "empty" placeholder row).
     */
    private function assertHasDataRows(string $body, string $needle): void
    {
        $this->assertStringContainsString(
            $needle,
            $body,
            "Expected data row containing '{$needle}' not found in print view body.",
        );
    }

    // ====================================================================
    // PER-MODULE PRINT TESTS
    // ====================================================================

    public function test_branch_print_returns_200(): void
    {
        $this->actingAsRole('admin');
        $branch = Branch::factory()->create([
            'branch_code' => 'PRBR-' . substr(uniqid(), -4),
            'branch_name' => 'Printable Branch',
        ]);

        $body = $this->assertPrintResponse(
            $this->get(route('admin.branches.print')),
            'branches',
            ['Code', 'Branch Name'],
        );

        $this->assertHasDataRows($body, 'Printable Branch');
    }

    public function test_warehouse_print_returns_200(): void
    {
        $this->actingAsRole('admin');
        $branch = Branch::factory()->create(['branch_name' => 'WH-Print-Branch']);
        $wh = Warehouse::factory()->forBranch($branch->id)->create([
            'warehouse_code' => 'PRWH-' . substr(uniqid(), -4),
            'warehouse_name' => 'Printable Warehouse',
        ]);

        $body = $this->assertPrintResponse(
            $this->get(route('admin.warehouses.print')),
            'warehouses',
            ['Code', 'Warehouse Name', 'Branch Name'],
        );

        $this->assertHasDataRows($body, 'Printable Warehouse');
    }

    public function test_product_print_returns_200(): void
    {
        $this->actingAsRole('admin');
