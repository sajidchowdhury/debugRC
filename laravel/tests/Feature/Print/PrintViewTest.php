    // ====================================================================
    // AUTH + RBAC
    // ====================================================================

    public function test_print_requires_auth(): void
    {
        // No actingAs — should redirect to login.
        $this->get(route('admin.branches.print'))
            ->assertRedirect(route('login'));
    }

    public function test_print_requires_manager_role(): void
    {
        // Salesman has no access to branches (admin/manager/warehouse_manager).
        $this->actingAsRole('salesman')
            ->get(route('admin.branches.print'))
            ->assertRedirect(route('dashboard'));
    }

    // ====================================================================
    // CONTENT-LEVEL ASSERTIONS
    // ====================================================================

    public function test_print_view_contains_table_headers(): void
    {
        $this->actingAsRole('admin');
        Branch::factory()->create();

        $body = $this->assertPrintResponse(
            $this->get(route('admin.branches.print')),
            'branches',
            ['Code', 'Branch Name', 'Address', 'Phone', 'Email'],
        );

        // Table structure: thead + tbody.
        $this->assertStringContainsString('<thead>', $body);
        $this->assertStringContainsString('<tbody>', $body);
    }

    public function test_print_view_contains_data_rows(): void
    {
        $this->actingAsRole('admin');
        Branch::factory()->create(['branch_name' => 'Unique Print Row Branch']);
        Branch::factory()->create(['branch_name' => 'Another Print Row Branch']);

        $body = $this->assertPrintResponse(
            $this->get(route('admin.branches.print')),
            'branches',
        );

        $this->assertHasDataRows($body, 'Unique Print Row Branch');
        $this->assertHasDataRows($body, 'Another Print Row Branch');
    }

    public function test_print_view_has_print_button(): void
    {
        $this->actingAsRole('admin');
        Branch::factory()->create();

        $response = $this->get(route('admin.branches.print'));
        $response->assertOk();

        $body = $response->getContent();

        // The shared layout's print toolbar button.
        $this->assertStringContainsString('window.print()', $body);
        // The "no-print" class hides it when actually printing.
        $this->assertStringContainsString('no-print', $body);
        // The printer icon (FontAwesome) should be present.
        $this->assertStringContainsString('fa-print', $body);
    }
}
