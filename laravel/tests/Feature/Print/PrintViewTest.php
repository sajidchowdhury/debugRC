    public function test_user_print_returns_200(): void
    {
        $this->actingAsRole('admin');
        $branch = Branch::factory()->create();
        $employee = Employee::factory()->forBranch($branch->id)->withRole('manager')->create([
            'name' => 'Printable Linked Employee',
        ]);
        User::factory()->forEmployee($employee->id)->create([
            'username' => 'pruser_' . substr(uniqid(), -4),
        ]);

        $body = $this->assertPrintResponse(
            $this->get(route('admin.users.print')),
            'users',
            ['Username', 'Employee Name'],
        );

        $this->assertStringContainsString('pruser_', $body);
    }

    public function test_ledger_print_returns_200(): void
    {
